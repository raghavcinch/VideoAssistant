@dataclass
class StabilizeAgent:
    name: str = "stabilize"

    def run(self, ctx: AgentContext) -> AgentResult:
        if not ctx.stabilize_first:
            return AgentResult(name=self.name, ok=True, summary="Skipped stabilization")

        idx_path = ctx.va_dir / "index.json"
        if not idx_path.exists():
            return AgentResult(name=self.name, ok=False, summary=f"Missing index: {idx_path}")

        stabilized_dir = ctx.stabilized_dir or (ctx.va_dir / "stabilized")
        stabilized_dir.mkdir(parents=True, exist_ok=True)

        # Backup raw index.
        raw_backup = ctx.va_dir / "index_raw.json"
        if not raw_backup.exists():
            raw_backup.write_text(idx_path.read_text(encoding="utf-8"), encoding="utf-8")

        idx = read_json(idx_path)
        clips = idx.get("clips", [])

        rooms: dict[str, list[str]] = {}
        out_dir_by_room: dict[str, str] = {}
        for clip in clips:
            room = clip.get("room") or "unknown"
            rooms.setdefault(room, []).append(clip["path"])
            room_dir = stabilized_dir / room
            out_dir_by_room[room] = str(room_dir)

        stabilize_script = ctx.va_dir / "resolve_stabilize_render.py"
        payload = {
            "project_name": ctx.project_name,
            "rooms": rooms,
            "out_dir_by_room": out_dir_by_room,
            "render_preset": ctx.stabilize_render_preset,
            "render_format": ctx.stabilize_render_format,
            "render_codec": ctx.stabilize_render_codec,
            "interactive": bool(getattr(ctx, 'stabilize_interactive', False)),
        }
        _write_resolve_stabilize_script(stabilize_script, payload)

        # Run Resolve script using the same interpreter running the assistant.
        # Resolve must already be running and have scripting enabled.
        import subprocess

        t0 = time.time()
        if getattr(ctx, 'stabilize_interactive', False):
            # In interactive mode, inherit the terminal stdio so input() prompts work.
            proc = subprocess.run([sys.executable, str(stabilize_script)], text=True)
        else:
            proc = subprocess.run([sys.executable, str(stabilize_script)], capture_output=True, text=True)
        dt = time.time() - t0
        warnings: list[str] = []
        if proc.returncode != 0:
            return AgentResult(
                name=self.name,
                ok=False,
                summary=f"Resolve stabilization script failed (exit={proc.returncode}).\n{proc.stderr.strip()}",
                artifacts={"stabilize_script": str(stabilize_script)},
            )

        # Only available when capture_output=True.
        if getattr(proc, 'stderr', None) and proc.stderr and proc.stderr.strip():
            warnings.append(proc.stderr.strip())
        if getattr(proc, 'stdout', None) and proc.stdout and proc.stdout.strip():
            warnings.append(proc.stdout.strip())

        # Update index.json paths to stabilized renders.
        updated = 0
        missing = 0
        for clip in clips:
            src = Path(clip["path"])
            room = clip.get("room") or "unknown"
            rendered = _find_rendered_file(stabilized_dir / room, src)
            if rendered:
                clip["path"] = str(rendered)
                updated += 1
            else:
                missing += 1

        idx["clips"] = clips
        idx["stabilized"] = True
        idx["stabilized_dir"] = str(stabilized_dir)
        write_json(idx_path, idx)

        # Stabilization QC: compare a quick shakiness score between original and stabilized.
        qc_enabled = bool(getattr(ctx, 'stabilize_qc', True))
        qc_path = ctx.va_dir / 'stabilization_qc.json'
        regressions = []
        qc = {
            'sample_fps': float(getattr(ctx, 'stabilize_qc_sample_fps', 3.0)),
            'scale_width': int(getattr(ctx, 'stabilize_qc_scale_width', 256)),
            'max_frames': int(getattr(ctx, 'stabilize_qc_max_frames', 96)),
            'regression_ratio': float(getattr(ctx, 'stabilize_qc_regression_ratio', 1.15)),
            'clips': {},
        }
        if qc_enabled and raw_backup.exists():
            try:
                raw_idx = read_json(raw_backup)
                raw_by_rel = {c.get('rel'): c for c in (raw_idx.get('clips') or []) if c.get('rel')}
            except Exception:
                raw_by_rel = {}

            clip_by_rel = {c.get('rel'): c for c in clips if c.get('rel')}

            for clip in clips:
                rel = clip.get('rel')
                raw_clip = raw_by_rel.get(rel) if rel else None
                raw_path = Path(raw_clip['path']) if (raw_clip and raw_clip.get('path')) else None
                stab_path = Path(clip['path']) if clip.get('path') else None
                if not (raw_path and stab_path and raw_path.exists() and stab_path.exists()):
                    continue

                raw_score, raw_meta = quick_shakiness_score(
                    raw_path,
                    sample_fps=qc['sample_fps'],
                    scale_width=qc['scale_width'],
                    max_frames=qc['max_frames'],
                )
                stab_score, stab_meta = quick_shakiness_score(
                    stab_path,
                    sample_fps=qc['sample_fps'],
                    scale_width=qc['scale_width'],
                    max_frames=qc['max_frames'],
                )
                qc['clips'][rel or str(raw_path)] = {
                    'raw_path': str(raw_path),
                    'stabilized_path': str(stab_path),
                    'raw_score': raw_score,
                    'stabilized_score': stab_score,
                    'raw_meta': raw_meta,
                    'stabilized_meta': stab_meta,
                }

                if raw_score is None or stab_score is None or raw_score <= 0:
                    continue
                ratio = float(stab_score / raw_score)
                if ratio >= float(qc['regression_ratio']):
                    regressions.append({'rel': rel, 'ratio': ratio, 'raw_score': raw_score, 'stabilized_score': stab_score})

            # Optional: OpenCV fallback for regressed clips (non-interactive).
            opencv_fallbacks: list[dict] = []
            if regressions and bool(getattr(ctx, 'stabilize_opencv_fallback', False)):
                qc['regressions_resolve'] = list(regressions)
                fallback_dir = stabilized_dir.parent / f"{stabilized_dir.name}_cv"
                fallback_dir.mkdir(parents=True, exist_ok=True)

                ocv_settings = OpenCVStabilizeSettings(
                    mode=str(getattr(ctx, 'opencv_mode', 'translation')),
                    smooth_seconds=float(getattr(ctx, 'opencv_smooth_seconds', 0.5)),
                    zoom=float(getattr(ctx, 'opencv_zoom', 1.06)),
                )

                for r in regressions:
                    rel = r.get('rel')
                    if not rel:
                        continue
                    raw_clip = raw_by_rel.get(rel)
                    stab_clip = clip_by_rel.get(rel)
                    if not (raw_clip and stab_clip):
                        continue
                    raw_path = Path(raw_clip.get('path') or '')
                    if not raw_path.exists():
                        continue

                    room = stab_clip.get('room') or raw_clip.get('room') or 'unknown'
                    out_room_dir = fallback_dir / str(room)
                    out_room_dir.mkdir(parents=True, exist_ok=True)
                    out_path = out_room_dir / f"{raw_path.stem}_cv_{ocv_settings.mode}.mp4"

                    try:
                        meta = stabilize_video_opencv(raw_path, out_path, ocv_settings)
                        stab_clip['path'] = str(out_path)
                        opencv_score, opencv_meta = quick_shakiness_score(
                            out_path,
                            sample_fps=qc['sample_fps'],
                            scale_width=qc['scale_width'],
                            max_frames=qc['max_frames'],
                        )

                        entry = qc['clips'].get(rel)
                        if isinstance(entry, dict):
                            entry['opencv_path'] = str(out_path)
                            entry['opencv_meta'] = {**meta, **(opencv_meta or {})}
                            entry['opencv_score'] = opencv_score
                            if (entry.get('raw_score') is not None) and (opencv_score is not None) and float(entry['raw_score']) > 0:
                                entry['opencv_ratio'] = float(opencv_score) / float(entry['raw_score'])

                        opencv_fallbacks.append(
                            {
                                'rel': rel,
                                'room': room,
                                'raw_path': str(raw_path),
                                'opencv_path': str(out_path),
                                'opencv_score': opencv_score,
                            }
                        )
                    except Exception as e:
                        warnings.append(f"OpenCV fallback failed for {rel}: {e}")

                if opencv_fallbacks:
                    qc['opencv_fallbacks'] = opencv_fallbacks
                    qc['opencv_fallback_dir'] = str(fallback_dir)
                    ctx.artifacts['stabilized_cv_dir'] = fallback_dir

                    # Recompute regressions list based on the *effective* stabilized paths (after fallback).
                    regressions_after = []
                    for clip in clips:
                        rel = clip.get('rel')
                        raw_clip = raw_by_rel.get(rel) if rel else None
                        raw_path = Path(raw_clip['path']) if (raw_clip and raw_clip.get('path')) else None
                        eff_path = Path(clip['path']) if clip.get('path') else None
                        if not (rel and raw_path and eff_path and raw_path.exists() and eff_path.exists()):
                            continue
                        raw_score = qc['clips'].get(rel, {}).get('raw_score')
                        if raw_score is None or float(raw_score) <= 0:
                            continue
                        eff_score, _eff_meta = quick_shakiness_score(
                            eff_path,
                            sample_fps=qc['sample_fps'],
                            scale_width=qc['scale_width'],
                            max_frames=qc['max_frames'],
                        )
                        if eff_score is None:
                            continue
                        ratio = float(eff_score) / float(raw_score)
                        if ratio >= float(qc['regression_ratio']):
                            regressions_after.append(
                                {
                                    'rel': rel,
                                    'ratio': ratio,
                                    'raw_score': raw_score,
                                    'effective_score': eff_score,
                                    'effective_path': str(eff_path),
                                }
                            )
                    regressions_after.sort(key=lambda rr: rr.get('ratio', 0), reverse=True)
                    qc['regressions_after_fallback'] = regressions_after
                    regressions = regressions_after

                    # Persist the updated index so downstream analysis uses fallback outputs.
                    idx['clips'] = clips
                    write_json(idx_path, idx)

            regressions.sort(key=lambda r: r.get('ratio', 0), reverse=True)
            qc['regressions'] = regressions
            write_json(qc_path, qc)
            ctx.artifacts['stabilization_qc'] = qc_path

            if regressions:
                top = regressions[:10]
                warnings.append(
                    'Stabilization QC: some clips got shakier after stabilization (likely Perspective warping). '
                    'See stabilization_qc.json; consider re-stabilizing those with Similarity/Translation. '
                    + 'Top: ' + ', '.join([str(r.get('rel')) for r in top if r.get('rel')])
                )

        if missing:
            warnings.append(f"Missing stabilized renders for {missing} clips; kept original paths for those.")

        # Always remind about Resolve mode limitation when stabilization is enabled.
        mode_hint = getattr(ctx, 'stabilize_mode_hint', None)
        warnings.append(
            'Resolve stabilization mode is controlled in the UI (Inspector > Stabilization > Mode); '
            + (f"current run hint='{mode_hint}'. " if mode_hint else '')
            + 'Resolve scripting does not expose per-clip mode switching reliably.'
        )

        ctx.artifacts["stabilized_dir"] = stabilized_dir
        ctx.artifacts["stabilize_script"] = stabilize_script
        return AgentResult(
            name=self.name,
            ok=True,
            summary=f"Stabilized and rendered clips (updated={updated}, seconds={dt:.1f})",
            artifacts={
                "stabilize_script": str(stabilize_script),
                "stabilized_dir": str(stabilized_dir),
                **({"stdout": proc.stdout.strip()} if getattr(proc, 'stdout', None) else {}),
                **({"stabilization_qc": str(qc_path)} if qc_enabled and qc_path.exists() else {}),
            },
            warnings=warnings,
        )
