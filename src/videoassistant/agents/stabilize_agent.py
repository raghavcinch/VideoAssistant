def find_timeline_by_name(proj, name: str):
    try:
        count = int(proj.GetTimelineCount())
    except Exception:
        return None
    for i in range(1, count + 1):
        tl = proj.GetTimelineByIndex(i)
        if tl and tl.GetName() == name:
            return tl
    return None


def ensure_unique_timeline(proj, media_pool, base_name: str):
    name = base_name
    i = 2
    while find_timeline_by_name(proj, name):
        name = f"{base_name}_{i}"
        i += 1
    try:
        tl = media_pool.CreateEmptyTimeline(name)
    except Exception:
        tl = None
    return tl or find_timeline_by_name(proj, name)


def ensure_project(pm, project_name: str):
    proj = pm.LoadProject(project_name)
    if proj:
        return proj
    try:
        cur = pm.GetCurrentProject()
    except Exception:
        cur = None
    if cur:
        return cur
    proj = pm.CreateProject(project_name)
    if not proj:
        raise SystemExit('Failed to create project: ' + project_name)
    return proj


def ensure_bin(media_pool, parent, name: str):
    for b in parent.GetSubFolderList() or []:
        if b.GetName() == name:
            return b
    return media_pool.AddSubFolder(parent, name)


def stabilize_timeline_items(timeline):
    # Stabilize all video items in track 1.
    items = []
    try:
        items = timeline.GetItemListInTrack('video', 1) or []
    except Exception:
        items = []
    ok_count = 0
    for it in items:
        try:
            if it.Stabilize():
                ok_count += 1
        except Exception:
            pass
    return ok_count, len(items)


def interactive_pause_before_stabilize(resolve, project, timeline, room: str):
    '''Pause to let user apply Stabilization attributes in the Resolve UI.

    Resolve's scripting API does not reliably expose Stabilizer Mode (Perspective/Similarity/Translation).
    The only reliable way to force Similarity/Translation is to set/paste clip attributes in the UI.
    '''

    try:
        project.SetCurrentTimeline(timeline)
    except Exception:
        pass
    try:
        resolve.OpenPage('edit')
    except Exception:
        pass

    print('--- Stabilization Settings (UI) ---')
    print('Room:', room)
    print('Open the timeline "' + (timeline.GetName() if timeline else '') + '" in Resolve.')
    print('1) Click the FIRST clip, Inspector > Stabilization > Mode = Similarity (or Translation).')
    print('2) Copy that clip.')
    print('3) Select ALL clips in the timeline, Paste Attributes... and enable Stabilization.')
    print('Then return here.')
    input('Press Enter to stabilize+render this room...')


def add_render_job_for_current_timeline(project, resolve, target_dir: str, render_preset: str | None, render_format: str | None, render_codec: str | None):
    resolve.OpenPage('deliver')

    if render_preset:
        try:
            project.LoadRenderPreset(render_preset)
        except Exception:
            pass

    def _pick_format_codec():
        # Prefer MP4 + H.265 for YouTube uploads; fall back to H.264; then fall back to whatever exists.
        try:
            formats = project.GetRenderFormats() or {}
        except Exception:
            formats = {}

        # Resolve returns format keys like "MP4", "MKV", "QuickTime".
        formats_lc = {str(k).lower(): k for k in formats.keys()}

        def pick_codec_for(fmt_key: str):
            try:
                codecs = project.GetRenderCodecs(fmt_key) or {}
            except Exception:
                codecs = {}
            # codecs is dict: description -> codecName
            def find(pred):
                for desc, name in codecs.items():
                    d = (desc or "").lower()
                    n = (name or "").lower()
                    if pred(d) or pred(n):
                        return name
                return None

            # Prefer NVIDIA encoders when available.
            c = find(lambda s: ("265" in s or "hevc" in s or "h.265" in s) and ("nvidia" in s))
            if c:
                return c
            c = find(lambda s: ("265" in s or "hevc" in s or "h.265" in s))
            if c:
                return c

            c = find(lambda s: ("264" in s or "avc" in s or "h.264" in s) and ("nvidia" in s))
            if c:
                return c
            c = find(lambda s: ("264" in s or "avc" in s or "h.264" in s))
            if c:
                return c
            # fall back to first codec name
            for _, name in codecs.items():
                return name
            return None

        for fmt_lc in ["mp4", "mkv", "quicktime"]:
            fmt_key = formats_lc.get(fmt_lc)
            if fmt_key:
                c = pick_codec_for(fmt_key)
                if c:
                    return fmt_key, c

        # any other format
        for fmt in formats.keys():
            c = pick_codec_for(fmt)
            if c:
                return fmt, c
        return None, None

    fmt = render_format
    cdc = render_codec
    if not (fmt and cdc):
        fmt, cdc = _pick_format_codec()
    if fmt and cdc:
        try:
            project.SetCurrentRenderFormatAndCodec(fmt, cdc)
        except Exception:
            pass

    # Individual clips
    try:
        project.SetCurrentRenderMode(0)
    except Exception:
        pass

    project.SetRenderSettings({
        'TargetDir': target_dir,
        'SelectAllFrames': 1,
    })
    return project.AddRenderJob()


def wait_for_render(project):
    while True:
        try:
            if not project.IsRenderingInProgress():
                return
        except Exception:
            return
        time.sleep(1)


