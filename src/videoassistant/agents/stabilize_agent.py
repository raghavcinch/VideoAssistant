def _find_rendered_file(room_dir: Path, source_path: Path) -> Path | None:
    """Best-effort mapping from source clip to rendered stabilized file.

    Resolve's "Individual clips" render will usually keep the source clip name.
    We match by stem (case-insensitive) and pick the newest file.
    """

    if not room_dir.exists():
        return None
    stem = source_path.stem.lower()
    matches: list[Path] = []
    for p in room_dir.glob("*"):
        if not p.is_file():
            continue
        cand = p.stem.lower()
        if cand == stem or cand.startswith(stem) or (stem in cand):
            matches.append(p)
    if not matches:
        return None
    matches.sort(key=lambda x: x.stat().st_mtime, reverse=True)
    return matches[0]


